#!/bin/bash
# ────────────────────────────────────────────────────────────
#  MOEX Bot — ежедневный отчёт в Telegram (19:00 МСК)
#
#  Добавить в crontab (crontab -e):
#    0 16 * * 1-5 /полный/путь/до/trader/run_report.sh >> /полный/путь/до/trader/logs/report.log 2>&1
#    (16:00 UTC = 19:00 МСК)
#
#  Проверить UTC-смещение: если сервер в другом поясе —
#    скорректируй час (например, 17:00 UTC = 20:00 МСК).
# ────────────────────────────────────────────────────────────

cd "$(dirname "$0")"

# Загружаем переменные окружения из .env (тот же .env что у бота)
if [ -f .env ]; then
    set -a
    source .env
    set +a
fi

echo "$(date '+%Y-%m-%d %H:%M:%S') — Запуск ежедневного отчёта..."
python3 daily_report.py
echo "$(date '+%Y-%m-%d %H:%M:%S') — Готово."
